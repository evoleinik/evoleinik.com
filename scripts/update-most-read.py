#!/usr/bin/env python3
"""Rewrite data/most_read.yaml from Vercel Web Analytics: the most-viewed posts, all time.

  scripts/update-most-read.py          print the new ranking, change nothing
  scripts/update-most-read.py --write  also rewrite data/most_read.yaml

Needs VERCEL_TOKEN (read from the environment, else from ~/.secrets). Views are pageviews per
post since analytics began; broken paths such as /posts/x/null are folded into nothing.
Exit 0 on success, 1 on an API or data error.
"""
import datetime, json, os, re, subprocess, sys, urllib.parse, urllib.request
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEAM, PROJECT, TOP = "team_PpQBzlDxT9O5QltmhwPVMEcN", "evoleinik-com", 5


def token():
    value = os.environ.get("VERCEL_TOKEN") or subprocess.run(
        ["bash", "-c", "set -a; source ~/.secrets >/dev/null 2>&1; printf %s \"${VERCEL_TOKEN:-}\""],
        capture_output=True, text=True).stdout
    if not value:
        sys.exit("VERCEL_TOKEN missing (environment or ~/.secrets)")
    return value


def get(tok, path, **query):
    req = urllib.request.Request("https://api.vercel.com" + path + "?" + urllib.parse.urlencode(query),
                                 headers={"Authorization": "Bearer " + tok})
    with urllib.request.urlopen(req, timeout=30) as response:
        return json.load(response)


def main():
    tok = token()
    pid = next(p["id"] for p in get(tok, "/v9/projects", teamId=TEAM, limit=100)["projects"] if p["name"] == PROJECT)
    rows = get(tok, "/v1/query/web-analytics/visits/aggregate", projectId=pid, teamId=TEAM, by="requestPath",
               limit=100, since="2025-12-14", until=str(datetime.date.today() + datetime.timedelta(days=1)),
               environment="production")["data"]
    published = {p.stem for p in (ROOT / "content/posts").glob("*.md")}
    views = Counter()
    for row in rows:
        match = re.fullmatch(r"/posts/([a-z0-9-]+)/?", row["requestPath"])
        if match and match.group(1) in published:
            views[match.group(1)] += row["pageviews"]
    ranking = views.most_common(TOP)
    if len(ranking) < 3:
        sys.exit(f"only {len(ranking)} posts have views; refusing to write a thin list")
    text = (f"# Generated by scripts/update-most-read.py on {datetime.date.today()}; lifetime pageviews.\n"
            "# The numbers are never shown on the site, only the order.\nposts:\n"
            + "".join(f"  - slug: {slug}\n    views: {count}\n" for slug, count in ranking))
    print(text, end="")
    if "--write" in sys.argv:
        (ROOT / "data/most_read.yaml").write_text(text)


if __name__ == "__main__":
    main()
